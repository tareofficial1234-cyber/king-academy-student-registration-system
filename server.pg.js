async function nextRegistrationId() {
  const year = new Date().getFullYear();
  const r = await pool.query(
    "SELECT registration_id FROM students WHERE registration_id LIKE $1 ORDER BY id DESC LIMIT 1",
    [`KA${year}%`],
  );
  const m = r.rows[0]?.registration_id?.match(/(\d{4})$/);
  const n = m ? Number(m[1]) + 1 : 1;
  return `KA${year}${String(n).padStart(4, "0")}`;
}
async function resultForStudent(studentId, academicYear) {
  const sr = await pool.query("SELECT * FROM students WHERE id=$1", [
    studentId,
  ]);
  const student = sr.rows[0];
  if (!student) return null;
  const mr = await pool.query(
    "SELECT * FROM marks WHERE student_id=$1 AND academic_year=$2 ORDER BY subject",
    [studentId, academicYear],
  );
  const marks = mr.rows;
  const total = marks.reduce((a, r) => a + Number(r.score), 0);
  const max_total = marks.reduce((a, r) => a + Number(r.max_score), 0);
  const average = max_total ? (total / max_total) * 100 : 0;
  return {
    student,
    academic_year: academicYear,
    marks,
    total,
    max_total,
    average: Number(average.toFixed(2)),
    subjects_count: marks.length,
    result: marks.length ? (average >= 50 ? "PASS" : "FAIL") : "NO MARKS",
  };
}
async function rankedResults(academicYear, grade) {
  const args = grade ? [grade] : [];
  const sql = `SELECT * FROM students ${grade ? "WHERE grade=$1" : ""} ORDER BY grade, last_name, first_name`;
  const students = (await pool.query(sql, args)).rows;
  const rows = [];
  for (const s of students) {
    const r = await resultForStudent(s.id, academicYear);
    if (r && r.marks.length) rows.push(r);
  }
  rows.sort(
    (a, b) =>
      b.average - a.average ||
      b.total - a.total ||
      studentName(a.student).localeCompare(studentName(b.student)),
  );
  let lastAvg = null,
    lastTotal = null,
    rank = 0;
  rows.forEach((r, i) => {
    if (lastAvg !== r.average || lastTotal !== r.total) rank = i + 1;
    r.rank = rank;
    lastAvg = r.average;
    lastTotal = r.total;
  });
  return rows;
}
