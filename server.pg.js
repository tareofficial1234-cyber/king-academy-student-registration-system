async function initDb() {
  await pool.query(`CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id TEXT UNIQUE NOT NULL, first_name TEXT NOT NULL, middle_name TEXT, last_name TEXT NOT NULL,
    gender TEXT NOT NULL, date_of_birth TEXT, grade TEXT NOT NULL, program TEXT, academic_year TEXT,
    admission_date TEXT, phone TEXT, email TEXT, address TEXT, guardian_name TEXT, guardian_phone TEXT,
    status TEXT NOT NULL DEFAULT 'Pending', photo TEXT, document TEXT, notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  await pool.query(`CREATE TABLE IF NOT EXISTS activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, action TEXT NOT NULL, description TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  await pool.query(`CREATE TABLE IF NOT EXISTS subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  await pool.query(`CREATE TABLE IF NOT EXISTS marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    academic_year TEXT NOT NULL, grade TEXT NOT NULL, subject TEXT NOT NULL, score DOUBLE PRECISION NOT NULL DEFAULT 0,
    max_score DOUBLE PRECISION NOT NULL DEFAULT 100, remark TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(student_id, academic_year, subject)
  )`);
  // Additive compatibility for existing Neon tables; does not delete or reseed records.
  await pool.query(
    "ALTER TABLE students ADD COLUMN IF NOT EXISTS academic_year TEXT",
  );
  await pool.query(
    "ALTER TABLE students ADD COLUMN IF NOT EXISTS admission_date TEXT",
  );
  // Intentionally do not seed subjects or sample students during migration testing.
}
function currentAcademicYear() {
  const d = new Date();
  const y = d.getFullYear();
  const start = d.getMonth() >= 8 ? y : y - 1;
  return `${start}/${String(start + 1).slice(-2)}`;
}
function yearList() {
  const y = parseInt(currentAcademicYear(), 10);
  return [
    ...new Set([
      currentAcademicYear(),
      `${y - 1}/${String(y).slice(-2)}`,
      `${y - 2}/${String(y - 1).slice(-2)}`,
      "2025/26",
      "2024/25",
    ]),
  ];
}
function studentName(s) {
  return [s.first_name, s.middle_name, s.last_name].filter(Boolean).join(" ");
}
function gradeSortValue(g = "") {
  if (g.startsWith("KG ")) return Number(g.slice(3));
  return 4 + Number(g.replace("Grade ", ""));
}
